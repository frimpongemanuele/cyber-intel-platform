"""Generate deployment configuration from the source registry (single source of truth).

    python -m cyberintel.deploy squid [--config config/sources.toml] [--ai-host HOST]...

The egress proxy (THREAT_MODEL T1, ARCHITECTURE section 7) is the network-level copy of
the application allowlist. Generating it from ``config/sources.toml`` means the two can
never drift; CI regenerates it and fails if the committed file differs.

Policy: CONNECT to port 443 only (every source is https); no plain-HTTP forwarding, so
no caching, header rewriting or request smuggling surface. Two listeners, so each client
is limited to its own destinations: 3128 for collectors (source hosts), 3129 for the AI
runner (the configured model API host only). Destinations resolving to private,
loopback, link-local, CGNAT or metadata ranges are denied *after* DNS resolution,
which is the DNS-rebinding defence in proxy mode (net/fetch.py).
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Iterable, Sequence
from pathlib import Path

from cyberintel.sources import load_registry

HEADER = (
    "# GENERATED by `python -m cyberintel.deploy squid --ai-host api.anthropic.com`.\n"
    "# Do not edit by hand: change config/sources.toml and regenerate (CI checks for drift).\n"
)
_HOST = re.compile(r"^(?=.{1,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")

PRIVATE_DST = (
    "0.0.0.0/8", "10.0.0.0/8", "100.64.0.0/10", "127.0.0.0/8", "169.254.0.0/16",
    "172.16.0.0/12", "192.0.0.0/24", "192.168.0.0/16", "198.18.0.0/15", "224.0.0.0/4",
    "240.0.0.0/4", "::/128", "::1/128", "64:ff9b::/96", "fc00::/7", "fe80::/10", "ff00::/8",
)  # fmt: skip
# Not listed: ::ffff:0:0/96. Squid stores IPv4 addresses as IPv4-mapped IPv6, so that
# entry would mean "all of IPv4" (found in the first CI run; squid warned and dropped it).
# Mapped forms of private IPv4 ranges are covered by the IPv4 entries above.


def _check_hosts(hosts: Iterable[str]) -> list[str]:
    """Exact hosts, or ``.suffix`` (subdomains; squid's dstdomain uses the same syntax)."""
    out = sorted({h.lower() for h in hosts})
    for h in out:
        if not _HOST.match(h.removeprefix(".")):
            raise ValueError(f"not a plain DNS hostname: {h!r}")
    return out


def render_squid(ingest_hosts: Iterable[str], ai_hosts: Iterable[str] = ()) -> str:
    ingest = _check_hosts(ingest_hosts)
    ai = _check_hosts(ai_hosts)
    if not ingest:
        raise ValueError("no ingest hosts")
    lines = [
        HEADER,
        "http_port 3128 name=ingest",
        "http_port 3129 name=ai",
        "acl ingest_port myportname ingest",
        "acl ai_port myportname ai",
        "acl CONNECT method CONNECT",
        "acl https_port port 443",
        "acl private_dst dst " + " ".join(PRIVATE_DST),
        *(f"acl ingest_hosts dstdomain {h}" for h in ingest),
        *(f"acl ai_hosts dstdomain {h}" for h in ai),
        "",
        "http_access deny !CONNECT",
        "http_access deny !https_port",
        "http_access deny private_dst",
        "http_access allow ingest_port ingest_hosts",
        *(["http_access allow ai_port ai_hosts"] if ai else []),
        "http_access deny all",
        "",
        "# no caching, no identifying headers, logs to stdout, writable paths under /tmp",
        "cache deny all",
        "cache_mem 0 MB",
        "via off",
        "forwarded_for delete",
        "httpd_suppress_version_string on",
        "pid_filename /tmp/squid.pid",
        "coredump_dir /tmp",
        "access_log stdio:/dev/stdout",
        "cache_log stdio:/dev/stderr",
        "cache_store_log none",
        "logfile_rotate 0",
        "shutdown_lifetime 2 seconds",
        "# ICMP pinger needs CAP_NET_RAW, which the container deliberately does not have",
        "pinger_enable off",
        "",
    ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m cyberintel.deploy")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sq = sub.add_parser("squid", help="print the egress proxy configuration")
    sq.add_argument("--config", type=Path, default=Path("config/sources.toml"))
    sq.add_argument("--ai-host", action="append", default=[], help="model API host (repeatable)")
    args = ap.parse_args(argv)
    hosts = load_registry(args.config).allowed_hosts()
    sys.stdout.write(render_squid(hosts, args.ai_host))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
